function storageGet(key) {
  try { return localStorage.getItem(key); } catch { return null; }
}
function storageSet(key, value) {
  try { localStorage.setItem(key, value); } catch { /* Storage is optional. */ }
}

function applyLanguage(language, { animate = false, remember = false } = {}) {
  const selected = translations[language] ? language : 'en';
  const localizedText = [...document.querySelectorAll('[data-i18n]')];
  const visibleText = localizedText.filter((element) => {
    const bounds = element.getBoundingClientRect();
    return bounds.width > 0 && bounds.height > 0 && bounds.bottom >= 0 && bounds.top <= window.innerHeight;
  });
  const updateLanguage = () => {
    root.lang = selected;
    document.querySelectorAll('[data-i18n]').forEach((element) => {
      const value = translations[selected][element.dataset.i18n];
      if (value) element.textContent = value;
    });
    document.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
      const value = translations[selected][element.dataset.i18nAriaLabel];
      if (value) element.setAttribute('aria-label', value);
    });
    document.querySelectorAll('[data-i18n-title]').forEach((element) => {
      const value = translations[selected][element.dataset.i18nTitle];
      if (value) element.title = value;
    });
    document.title = translations[selected].page_title;
    document.querySelector('meta[name="description"]')?.setAttribute('content', translations[selected].page_description);
    document.querySelector('meta[property="og:title"]')?.setAttribute('content', translations[selected].page_title);
    document.querySelector('meta[property="og:description"]')?.setAttribute('content', translations[selected].page_description);
    document.querySelectorAll('[data-lang]').forEach((button) => {
      button.setAttribute('aria-pressed', String(button.dataset.lang === selected));
    });
    if (remember) storageSet('ah51-language-preference', selected);
    updateControlLabels();
  };

  clearTimeout(languageTextChangeTimer);
  clearTimeout(languageAnimationCleanupTimer);
  localizedText.forEach((element) => {
    element.classList.remove('i18n-text-out', 'i18n-text-in');
    element.style.removeProperty('--i18n-delay');
  });

  if (animate && selected !== root.lang) {
    visibleText.forEach((element) => element.classList.add('i18n-text-out'));
    languageTextChangeTimer = window.setTimeout(() => {
      updateLanguage();
      visibleText.forEach((element, index) => {
        element.classList.remove('i18n-text-out');
        element.style.setProperty('--i18n-delay', `${Math.min(index * 12, 144)}ms`);
        element.classList.add('i18n-text-in');
      });
      languageTextChangeTimer = null;
      languageAnimationCleanupTimer = window.setTimeout(() => {
        visibleText.forEach((element) => {
          element.classList.remove('i18n-text-out', 'i18n-text-in');
          element.style.removeProperty('--i18n-delay');
        });
        languageAnimationCleanupTimer = null;
      }, 640);
    }, 120);
  } else {
    updateLanguage();
  }
}

function detectDeviceLanguage() {
  const preferredLanguages = Array.isArray(navigator.languages) && navigator.languages.length
    ? navigator.languages
    : [navigator.language || 'en'];
  for (const preferredLanguage of preferredLanguages) {
    const baseLanguage = String(preferredLanguage).trim().toLowerCase().replace('_', '-').split('-')[0];
    if (translations[baseLanguage]) return baseLanguage;
  }
  return 'en';
}

function getInitialLanguage() {
  const savedPreference = storageGet('ah51-language-preference');
  if (translations[savedPreference]) return savedPreference;

  // Older versions saved the initial Indonesian default as if it were a manual choice.
  const legacyPreference = storageGet('ah51-language');
  if (legacyPreference && legacyPreference !== 'id' && translations[legacyPreference]) {
    storageSet('ah51-language-preference', legacyPreference);
    return legacyPreference;
  }
  return detectDeviceLanguage();
}

function applyTheme(theme) {
  const selected = theme === 'light' ? 'light' : 'dark';
  root.dataset.theme = selected;
  document.querySelector('meta[name="theme-color"]')?.setAttribute('content', selected === 'dark' ? '#101713' : '#f4f5ef');
  storageSet('ah51-theme', selected);
  updateControlLabels();
}

function updateControlLabels() {
  const language = root.lang || 'id';
  const strings = translations[language] || translations.id;
  const nextTheme = root.dataset.theme === 'dark' ? 'light' : 'dark';
  themeButton.setAttribute('aria-label', strings[nextTheme === 'light' ? 'theme_light' : 'theme_dark']);
  themeButton.title = themeButton.getAttribute('aria-label');
  const menuIsOpen = menuButton.getAttribute('aria-expanded') === 'true';
  menuButton.setAttribute('aria-label', strings[menuIsOpen ? 'menu_close' : 'menu_open']);
}

function showToast(message) {
  toast.textContent = message;
  toast.classList.add('visible');
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => toast.classList.remove('visible'), 2600);
}

document.querySelectorAll('[data-lang]').forEach((button) => {
  button.addEventListener('click', () => applyLanguage(button.dataset.lang, { animate: true, remember: true }));
});
themeButton.addEventListener('click', () => applyTheme(root.dataset.theme === 'dark' ? 'light' : 'dark'));
menuButton.addEventListener('click', () => {
  const open = menuButton.getAttribute('aria-expanded') !== 'true';
  menuButton.setAttribute('aria-expanded', String(open));
  nav.classList.toggle('open', open);
  updateControlLabels();
});
nav.querySelectorAll('a').forEach((link) => link.addEventListener('click', () => {
  menuButton.setAttribute('aria-expanded', 'false');
  nav.classList.remove('open');
  updateControlLabels();
}));
document.getElementById('share-btn').addEventListener('click', async () => {
  const strings = translations[root.lang] || translations.id;
  try {
    if (navigator.share) await navigator.share({ title: document.title, url: location.href });
    else if (navigator.clipboard?.writeText) {
      await navigator.clipboard.writeText(location.href);
      showToast(strings.share_done);
    } else throw new Error('Share unavailable');
  } catch (error) {
    if (error?.name !== 'AbortError') showToast(strings.share_error);
  }
});

